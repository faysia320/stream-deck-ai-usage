"""Regenerate com.local.aiusage.sdPlugin/glyphs.js from a font file.

Key text is drawn as SVG paths so its width is identical in every renderer;
Stream Deck substitutes fonts differently from browsers, which made text overflow.

Usage: python tools/build_glyphs.py roboto-condensed-latin-700-normal.woff
Requires fontTools (dev only). The bundled glyphs come from Roboto Condensed Bold
(SIL Open Font License 1.1, Copyright 2011 Google Inc.).
"""
import json
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

CHARS = "0123456789%-:/ ABCDEFGHIJKLMNOPQRSTUVWXYZ"
OUT = Path(__file__).resolve().parents[1] / "com.local.aiusage.sdPlugin" / "glyphs.js"

font = TTFont(sys.argv[1])
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
glyphs = {}
for char in CHARS:
    name = cmap[ord(char)]
    pen = SVGPathPen(glyph_set, lambda value: f"{value:.0f}")
    glyph_set[name].draw(pen)
    glyphs[char] = {"d": pen.getCommands(), "w": glyph_set[name].width}

data = {"em": font["head"].unitsPerEm, "cap": font["OS/2"].sCapHeight, "glyphs": glyphs}
OUT.write_text("// Generated by tools/build_glyphs.py from Roboto Condensed Bold (SIL OFL 1.1, Copyright 2011 Google Inc.; see glyphs-OFL.txt).\n"
               f"module.exports = {json.dumps(data, separators=(',', ':'))};\n", encoding="utf-8")
print(f"{OUT} ({OUT.stat().st_size} bytes)")
